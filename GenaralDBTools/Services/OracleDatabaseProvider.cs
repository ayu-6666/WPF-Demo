using System.Data;
using System.Data.Common;
using GenaralDBTools.Models;
using Oracle.ManagedDataAccess.Client;

namespace GenaralDBTools.Services;

public sealed class OracleDatabaseProvider : SqlProviderBase
{
    public override DatabaseKind Kind => DatabaseKind.Oracle;
    public override string DisplayName => "Oracle";

    protected override string ParameterPrefix => ":";

    protected override DbConnection CreateConnection(ConnectionProfile profile)
    {
        var builder = new OracleConnectionStringBuilder
        {
            UserID = profile.Username,
            Password = profile.Password,
            DataSource = $"{profile.Host}:{(profile.Port == 0 ? 1521 : profile.Port)}/{profile.Database}",
            ConnectionTimeout = 8
        };
        return new OracleConnection(builder.ConnectionString);
    }

    protected override string Quote(string identifier) => $"\"{identifier.Replace("\"", "\"\"")}\"";

    protected override string? ResolveOrderBy(IReadOnlyList<ColumnInfo> columns, bool isView)
    {
        var pk = columns.Where(c => c.IsPrimaryKey).Select(c => Quote(c.Name)).ToList();
        if (pk.Count > 0) return string.Join(", ", pk);
        return isView ? null : "ROWID";
    }

    protected override string PagedSql(string qualifiedTable, string? orderBy, string filter, int limit, int offset)
    {
        var where = filter is null ? "" : $" WHERE {filter}";
        var order = orderBy is null ? "" : $" ORDER BY {orderBy}";
        return $"SELECT * FROM {qualifiedTable}{where}{order} OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY";
    }

    protected override string BuildCreateTableSql(string qualifiedTable, IReadOnlyList<ColumnDefinition> columns)
    {
        if (columns.Count(c => c.IsAutoIncrement) > 1)
            throw new InvalidOperationException("一张表最多只能有一个自增字段。");

        var parts = new List<string>();
        foreach (var column in columns)
        {
            var clause = $"{Quote(column.Name)} {column.DataType}";
            if (!column.IsNullable) clause += " NOT NULL";
            if (column.IsAutoIncrement)
            {
                if (!column.IsPrimaryKey)
                    throw new InvalidOperationException("Oracle 的标识列必须同时设为主键。");
                clause += " GENERATED BY DEFAULT AS IDENTITY";
            }
            if (!string.IsNullOrWhiteSpace(column.DefaultValue)) clause += $" DEFAULT {column.DefaultValue.Trim()}";
            parts.Add(clause);
        }

        var pkColumns = columns.Where(c => c.IsPrimaryKey).Select(c => Quote(c.Name)).ToList();
        if (pkColumns.Count > 0)
            parts.Add($"PRIMARY KEY ({string.Join(", ", pkColumns)})");

        return $"CREATE TABLE {qualifiedTable} (\n  {string.Join(",\n  ", parts)}\n)";
    }

    public override async Task<IReadOnlyList<DatabaseNode>> GetObjectsAsync(ConnectionProfile profile, CancellationToken ct = default)
    {
        const string sql = """
            SELECT object_name, object_type FROM user_objects
            WHERE object_type IN ('TABLE','VIEW')
            ORDER BY CASE object_type WHEN 'TABLE' THEN 0 ELSE 1 END, object_name
            """;
        await using var connection = CreateConnection(profile);
        await connection.OpenAsync(ct);
        var data = await QueryAsync(connection, sql, ct);

        var nodes = new List<DatabaseNode>();
        foreach (DataRow row in data.Rows)
        {
            var name = Convert.ToString(row["object_name"]) ?? "";
            var isView = string.Equals(Convert.ToString(row["object_type"]), "VIEW", StringComparison.OrdinalIgnoreCase);
            nodes.Add(new DatabaseNode
            {
                Name = name,
                NodeType = isView ? NodeTypes.View : NodeTypes.Table,
                ProfileId = profile.Id,
                ObjectName = name,
                Icon = isView ? "◫" : "▦"
            });
        }
        if (nodes.Count == 0)
            nodes.Add(new DatabaseNode { Name = "（当前用户没有表）", NodeType = NodeTypes.Hint, Icon = "·" });
        return nodes;
    }

    public override async Task<IReadOnlyList<DatabaseNode>> GetChildObjectsAsync(ConnectionProfile profile, DatabaseNode node, CancellationToken ct = default)
    {
        if (!node.IsTableLike || string.IsNullOrWhiteSpace(node.ObjectName))
            return Array.Empty<DatabaseNode>();

        var columns = await GetColumnsAsync(profile, null, node.ObjectName, ct);
        if (columns.Count == 0)
            return new[] { new DatabaseNode { Name = "（无字段信息）", NodeType = NodeTypes.Hint, Icon = "·" } };

        return columns.Select(c => new DatabaseNode
        {
            Name = $"{c.Name}  {c.DataType}{(c.IsPrimaryKey ? " · PK" : "")}{(!c.IsNullable ? " · 非空" : "")}",
            NodeType = NodeTypes.Column,
            ProfileId = profile.Id,
            ObjectName = node.ObjectName,
            Icon = c.IsPrimaryKey ? "◇" : "◻"
        }).ToList();
    }

    public override async Task<IReadOnlyList<ColumnInfo>> GetColumnsAsync(ConnectionProfile profile, string? schema, string table, CancellationToken ct = default)
    {
        ValidateName(table, "表名");
        await using var connection = CreateConnection(profile);
        await connection.OpenAsync(ct);

        const string columnSql = """
            SELECT column_name, data_type, data_length, data_precision, data_scale,
                   nullable, data_default, hidden_column
            FROM user_tab_columns
            WHERE table_name = :table
            ORDER BY column_id
            """;
        await using var command = connection.CreateCommand();
        command.CommandText = columnSql;
        var tableParameter = command.CreateParameter();
        tableParameter.ParameterName = ":table";
        tableParameter.Value = table;
        command.Parameters.Add(tableParameter);
        var columns = await ReadTableAsync(command, ct);

        var pkColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        try
        {
            const string pkSql = """
                SELECT ucc.column_name
                FROM user_constraints uc
                JOIN user_cons_columns ucc
                  ON uc.constraint_name = ucc.constraint_name
                WHERE uc.constraint_type = 'P' AND uc.table_name = :table
                """;
            await using var pkCommand = connection.CreateCommand();
            pkCommand.CommandText = pkSql;
            var pkParameter = pkCommand.CreateParameter();
            pkParameter.ParameterName = ":table";
            pkParameter.Value = table;
            pkCommand.Parameters.Add(pkParameter);
            var pkData = await ReadTableAsync(pkCommand, ct);
            foreach (DataRow row in pkData.Rows)
                pkColumns.Add(Convert.ToString(row[0]) ?? "");
        }
        catch (OracleException)
        {
            // 主键元数据读取失败时按无主键处理，界面会明确提示无法安全更新/删除。
        }

        var identityColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        try
        {
            const string identitySql = """
                SELECT column_name FROM user_tab_identity_cols WHERE table_name = :table
                """;
            await using var identityCommand = connection.CreateCommand();
            identityCommand.CommandText = identitySql;
            var identityParameter = identityCommand.CreateParameter();
            identityParameter.ParameterName = ":table";
            identityParameter.Value = table;
            identityCommand.Parameters.Add(identityParameter);
            var identityData = await ReadTableAsync(identityCommand, ct);
            foreach (DataRow row in identityData.Rows)
                identityColumns.Add(Convert.ToString(row[0]) ?? "");
        }
        catch (OracleException)
        {
            // 11g 及更早版本没有标识列视图。
        }

        var list = new List<ColumnInfo>();
        foreach (DataRow row in columns.Rows)
        {
            var name = Convert.ToString(row["column_name"]) ?? "";
            var dataType = Convert.ToString(row["data_type"]) ?? "";
            var length = row["data_length"] is DBNull ? 0L : Convert.ToInt64(row["data_length"]);
            var precision = row["data_precision"] is DBNull ? (int?)null : Convert.ToInt32(row["data_precision"]);
            var scale = row["data_scale"] is DBNull ? (int?)null : Convert.ToInt32(row["data_scale"]);
            var displayType = dataType switch
            {
                "VARCHAR2" or "NVARCHAR2" or "CHAR" => $"{dataType}({length})",
                "NUMBER" when precision is > 0 && scale is > 0 => $"{dataType}({precision},{scale})",
                "NUMBER" when precision is > 0 => $"{dataType}({precision})",
                _ => dataType
            };
            var isPk = pkColumns.Contains(name);
            var nullable = string.Equals(Convert.ToString(row["nullable"]), "Y", StringComparison.OrdinalIgnoreCase) && !isPk;
            var isAuto = identityColumns.Contains(name);
            var defaultValue = row["data_default"] is DBNull or null ? null : Convert.ToString(row["data_default"])?.Trim();
            list.Add(new ColumnInfo(name, displayType, nullable, isPk, isAuto, defaultValue));
        }
        return list;
    }

    private static async Task<DataTable> ReadTableAsync(DbCommand command, CancellationToken ct)
    {
        await using var reader = await command.ExecuteReaderAsync(ct);
        var table = new DataTable("结果集");
        table.Load(reader);
        return table;
    }
}
